"""Generate paper/acme/tables/tab-models.tex (the model roster of the benchmark).

Rows come from analysis/acme/models.yaml (family, size in billions of parameters, precision, pinned revision) and the licence from
runs/models/MODELS.jsonl, whose revisions are asserted equal to the roster's (make_autonumbers.roster). The precision-control copy of one model
was removed from the paper after the red-team review of 2026-11-08 and is not listed. The valid-mass and near-deterministic columns are model outcomes and live in the supplement table.
The script checks the number of rows against the \\NUM key n.models and the split by precision against bm.models.nf4 and bm.models.bf16.

Usage:  python analysis/acme/make_tab_models.py [--out paper/acme/tables/tab-models.tex]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402  (records the files read, for the .source.json)
_REC = rc.record_reads()
from make_autonumbers import NUMBERS, roster, _WORDS  # noqa: E402

PREC = {"bf16": "bf16", "nf4_saved": "NF4"}
LIC = {"apache-2.0": "Apache-2.0", "mit": "MIT"}


def name(repo: str) -> str:
    return repo.split("/", 1)[1]


def build() -> str:
    rows = roster()
    main = [r for r in rows if r["control"] == "false"]
    ctl = [r for r in rows if r["control"] == "true"]
    assert str(len(main)) == NUMBERS["n.models"].value
    assert _WORDS[sum(r["quant"] == "nf4_saved" for r in main)] == NUMBERS["bm.models.nf4"].value
    assert _WORDS[sum(r["quant"] == "bf16" for r in main)] == NUMBERS["bm.models.bf16"].value
    assert len({r["repo"] for r in main}) == len(main)
    lines = [
        "% GENERATED by analysis/acme/make_tab_models.py from analysis/acme/models.yaml and runs/models/MODELS.jsonl. Do not edit by hand.",
        "% Size: billions of parameters. Revision: first eight characters of the pinned repository commit.",
        r"{\footnotesize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.05}",
        r"\begin{tabular}{@{}llrlll@{}}",
        r"\toprule",
        r"Model & Family & Size & Precision & License & Pinned revision \\",
        r"\midrule",
    ]
    for r in main:
        lines.append(f"{name(r['repo'])} & {r['family']} & {r['params_b']} & {PREC[r['quant']]} & {LIC[r['licence']]} & "
                     f"\\texttt{{{r['revision'][:8]}}} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "paper" / "acme" / "tables" / "tab-models.tex")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(), encoding="utf-8", newline="\n")
    rc.write_source_recorded([args.out], "analysis/acme/make_tab_models.py", _REC)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
