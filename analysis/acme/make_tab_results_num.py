"""Generate paper/acme/tables/tab-results-num.tex (key `results-num`): the numeric items (P2a, P2b, P2c, P2d, P4) and why they are not decomposed.

Per item, read from runs/ files (nothing typed in):
  models per roster: valid mass only, G4 per model and type (column (b)), Arm S strict (column (a)), intersection (column (e))   runs/acme-L/rosters.csv, route_table.csv
  Arm L status (column (b)): decomposed with n models, or not decomposed (fewer than 3 models; floor 3)                           route_table.csv
  Arm S column (a), E2: residual share, smallest and largest untruncated share (with the group of the largest)                    components_<item>.csv
  flags (derived by rule from those columns; the rule is printed in the table note):
    L  Arm L (b) not decomposed (fewer than 3 models)
    I  intersection (e) not decomposed (fewer than 3 models) or exactly the floor (3 models)
    U  an untruncated Arm S share lies outside [0, 1] by more than BIAS_RULE (E7a item 3)
    R  residual share of Arm S (a) at or above 0.5

    .venv/Scripts/python.exe -I analysis/acme/make_tab_results_num.py [--out paper/acme/tables/tab-results-num.tex]
Writes OUT and OUT.source.json.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402
import results_route as R  # noqa: E402

ITEM_TEX = {"P2a": "P2a", "P2b": "P2b", "P2c": "P2c", "P2d": "P2d", "P4": "P4"}
FLOOR = 3     # decomposability floor of route_table.py / route_inputs.py (the route table prints it in the note of an undecomposed item)


def build(route: R.Route, rosters, items: list[str]) -> str:
    L = [
        "% GENERATED by analysis/acme/make_tab_results_num.py from runs/acme-L/rosters.csv, runs/acme-gstudy/route-table/route_table.csv and",
        "% runs/acme-S-gstudy/route-a/components_<item>.csv. Do not edit by hand; rerun the script. <outfile>.source.json lists the SHA-256 of each input.",
        r"{\footnotesize\setlength{\tabcolsep}{3.6pt}\renewcommand{\arraystretch}{1.1}",
        r"\begin{tabular}{@{}l rrrrr c r r l l@{}}", r"\toprule",
        r" & \multicolumn{5}{c}{Models on the roster} & & \multicolumn{3}{c}{Arm S, column (a), E2 shares} & \\",
        r"\cmidrule(lr){2-6}\cmidrule(lr){8-10}",
        r"Item & \shortstack{Valid\\mass} & \shortstack{G4 per\\type (b)} & \shortstack{Strict\\(a)} & \shortstack{Inter-\\section (e)} & \shortstack{G4 per\\model (d)} & \shortstack{Arm L (b)\\decomposed} & Residual & Smallest & \shortstack{Largest\\(group)} & Flags \\",
        r"\midrule",
    ]
    for it in items:
        ro = rosters[rosters["item"] == it].iloc[0]
        ia, ib, ie = route.info("(a)", it), route.info("(b)", it), route.info("(e)-ArmS", it)
        n_a = ia["n_models"]
        n_e = ie["n_models"] if ie["n_models"] is not None else 0
        n_b = int(ro["per_type"])
        status = "yes" if ib["decomposed"] else "no"
        # Arm S (a) terms, E2
        x = route.rt[(route.rt["column"] == "(a)") & (route.rt["item"] == it) & (route.rt["basis"] == "E2") & route.rt["component"].notna()]
        x = x[x["component"] != "draw"]
        res = float(x[x["component"].isin(R.RES_NAMES)]["share"].iloc[0])
        mn, mx = float(x["share"].min()), float(x["share"].max())
        gmax = R.GROUP_TEX[R.group_of(x.loc[x["share"].idxmax(), "component"])]
        flags = []
        if not ib["decomposed"]:
            flags.append("L")
        if (not ie["decomposed"]) or n_e <= FLOOR:
            flags.append("I")
        if mn < -R.BIAS_RULE or mx > 1 + R.BIAS_RULE:
            flags.append("U")
        if res >= 0.5:
            flags.append("R")
        L.append(f"{ITEM_TEX[it]} & {int(ro['validmass_only'])} & {n_b} & {n_a} & {n_e} & {int(ro['per_model'])} & {status} & {R.tx(res)} & {R.tx(mn)} & {R.tx(mx)} ({gmax}) & {', '.join(flags) if flags else '--'} " + r"\\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\par\smallskip"]
    notes = [
        r"Models on the roster: after the valid-mass rule alone; after the pre-outcome G4 rule per model and type (the roster of column (b)); in the strict Arm S roster of column (a); on the intersection of the two (column (e)); and after the G4 rule per model (column (d), counts only).",
        rf"A decomposition needs at least {FLOOR} models; below that the item is not decomposed.",
        r"The residual and the smallest and largest shares are the untruncated E2 estimates of column (a) (four wordings, two orders, two temperatures, draw noise excluded from the residual); a negative value is a negative estimate of a variance component.",
        rf"Flags (set by rule from the columns): L, Arm L column (b) not decomposed; I, intersection roster not decomposed or at the floor of {FLOOR} models; "
        rf"U, an untruncated Arm S share outside [0, 1] by more than {R.BIAS_RULE:g}; R, residual share of at least 0.5.",
        r"The numeric items are not interpreted in this paper, for any column.",
    ]
    L.append(r"{\footnotesize\raggedright " + " ".join(notes) + r"\par}")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = rc.resolve_arg(a.out, rc.ROOT / "paper" / "acme" / "tables" / "tab-results-num.tex")
    R.base_guard([out], a.out is not None)
    tr = rc.Tracker()
    route = R.Route(tr)
    rosters = tr.csv(rc.ROOT / "runs" / "acme-L" / "rosters.csv", dtype={"item": str})
    items = R.items_order(tr, R.NUM_ITEMS)
    text = build(route, rosters, items)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf8")
    rc.write_source([out], "analysis/acme/make_tab_results_num.py", R.ROUTE, tr, extra=dict(items=items))


if __name__ == "__main__":
    main()
