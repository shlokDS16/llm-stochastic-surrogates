"""E7 route table, column (e): the like-for-like comparison on the intersection roster (post-outcome, exploratory, descriptive).

Intersection roster: a (model, item) pair is in when it is ok in runs/acme-S-gstudy/roster_strict.csv (Arm S, column (a)) AND not in
runs/acme-L/exclusions_per_type.csv (Arm L, column (b)). Items with fewer than 3 intersection models are not decomposed (the decomposability
floor of the agreed debate research/debates/2026-11-07-CRP-S09-acme-post-gate-analysis, round 3).

Writes
  runs/acme-S-gstudy/route-e-armS/roster_intersection.csv     model, item, ok (= both), ok_armS, excluded_armL   -> input of gstudy_armS.py
  runs/acme-gstudy/A1-route-e-armL/inputs/effects.csv         Arm L effects restricted to the intersection pairs, kept items, W0-W3,
                                                              T in {0.7, 1.0}, variant main (the cells Arm S has), + roster.json
  runs/acme-gstudy/A1-route-e-armL/prompt_identity.csv        per item and W0-W3: SHA-256 of the exact prompt text of Arm L and of Arm S, match
  runs/acme-gstudy/A1-route-e-armL/prompt_identity_detail.csv per item, W, order, x (prompt level), with the disk-versus-code checks
  runs/acme-gstudy/A1-route-e-armL/prompt_identity.json       provenance (manifest verification, source of each hash)
The frozen gstudy.py (--estimator A1, same scale.csv and se.csv as route_inputs.py) and gstudy_armS.py are then run by the caller.

Prompt text. Arm L: analysis/acme/prompts_acme.py build() with F0 (run_armL.py writes the system and turns of every prompt into its rows;
those rows are read from disk and compared with the rebuild). Arm S: new items AF, QA, NR are generated by run_armS.py, which calls the same
prompts_acme.build() with F0 (rows on disk do not store the prompt, so the rebuild is the evidence); the pilot items P1, P2a-d, P3, P4 come from
run_pilot_acme.py = analysis/pilot/run_pilot.py, whose rows store system and user (read from disk, compared with a rebuild by
run_pilot.build_prompt on the pilot common.yaml). Arm S has no order for P3 (forward scale only); it is compared with Arm L's 'forward' P3 prompts,
and Arm L's 'reversed' prompts have no Arm S counterpart (row 'no Arm S counterpart'). Mismatches are reported, never resolved.

    .venv/Scripts/python.exe -I analysis/acme/route_e_inputs.py
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "analysis" / "pilot"))

EFF = ROOT / "runs/acme-L/outcomes/effects.csv"
S_ROSTER = ROOT / "runs/acme-S-gstudy/roster_strict.csv"
L_EXCL = ROOT / "runs/acme-L/exclusions_per_type.csv"
OUT_S = ROOT / "runs/acme-S-gstudy/route-e-armS"
OUT_L = ROOT / "runs/acme-gstudy/A1-route-e-armL"
MIN_MODELS = 3
WS = ("W0", "W1", "W2", "W3")
TS = (0.7, 1.0)
ITEMS = ["P1", "AF", "NR", "P3", "QA", "P2a", "P2b", "P2c", "P2d", "P4"]
NEW = ("AF", "QA", "NR")
ORDERS_L = {"P1": ["sure_first", "risky_first"], "P3": ["forward", "reversed"], "QA": ["forward", "reversed"],
            "AF": ["yes_first", "no_first"], "NR": ["yes_first", "no_first"]}


def sha(obj) -> str:
    return hashlib.sha256(json.dumps(obj, ensure_ascii=False, sort_keys=True).encode("utf8")).hexdigest()


def canon(system, turns):
    return [system, [[r, t] for r, t in turns]]


def intersection():
    s = pd.read_csv(S_ROSTER)
    ex = pd.read_csv(L_EXCL, dtype=str)
    excl = set(zip(ex["model"], ex["item"]))
    s["ok_armS"] = s["ok"].astype(bool)
    s["excluded_armL"] = [(m, i) in excl for m, i in zip(s["model"], s["item"])]
    s["ok"] = s["ok_armS"] & ~s["excluded_armL"]
    return s[["model", "item", "ok", "ok_armS", "excluded_armL"]]


