"""RQ1 descriptive tables T-RQ1a..e (protocol v0.9 item 2: two abstract-coded views, neither is the headline).

    .venv/Scripts/python.exe -I analysis/rq1/rq1_tables.py

Views: A = liberal frame (2,022); B = coder-flagged yes within A; S = strict frame (1,470), sensitivity column.
Outputs: runs/rq1-tables/{config.json, rq1_tables.log, T-RQ1*.csv, summary.md, metrics.json}
         paper/tables/T-RQ1*.tex (booktabs)
A record can carry several paradigm families / model families / languages: those tables count records with at
least one item of the category, so columns do not sum to the denominator. T-RQ1d uses the FIRST listed family
(as in the sample design, v0.9.1) so that its rows sum to the view total.
"""
from __future__ import annotations

import csv
import json
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rq1_common as C  # noqa: E402

RUN = C.ROOT / "runs/rq1-tables"
TEX = C.ROOT / "paper/tables"
VIEWS = ["A", "B", "S"]
FLAGFILE = C.ROOT / "runs/fulltext-pilot/rq1-flag-crosstab.md"


def tex_esc(s: str) -> str:
    return str(s).replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")


def fmt_np(n, d):
    return f"{n} ({C.pct(n, d):.1f})"


def write_csv(path: Path, header, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def write_tex(path: Path, caption_note: str, header, body_rows, colspec, panels=None, resize=False):
    """body_rows: list of lists of strings; a row equal to ['\\midrule'] inserts a rule."""
    lines = ["% generated by analysis/rq1/rq1_tables.py; do not edit by hand", "\\begin{tabular}{" + colspec + "}", "\\toprule",
             " & ".join(tex_esc(h) if not h.startswith("\\") else h for h in header) + " \\\\", "\\midrule"]
    for r in body_rows:
        if r == ["\\midrule"]:
            lines.append("\\midrule")
        elif len(r) == 1 and r[0].startswith("\\multicolumn"):
            lines.append(r[0] + " \\\\")
        else:
            lines.append(" & ".join(tex_esc(c) for c in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", f"% {caption_note}"]
    txt = "\n".join(lines) + "\n"
    if resize:
        txt = txt.replace("\\begin{tabular}", "\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}", 1).replace("\\end{tabular}", "\\end{tabular}}", 1)
    path.write_text(txt, encoding="utf-8")


def count_table(name, items, flags, rows, views, denoms):
    """items: list of (label, fn(row)->bool). Returns csv rows [label, A_n, A_pct, B_n, B_pct, S_n, S_pct]."""
    out = []
    for label, fn in items:
        r = [label]
        for v in VIEWS:
            k = sum(1 for i in views[v] if fn(rows[i]))
            r += [k, C.pct(k, denoms[v])]
        out.append(r)
    return out


def main():
    RUN.mkdir(parents=True, exist_ok=True)
    TEX.mkdir(parents=True, exist_ok=True)
    log = C.setup_run(RUN, "rq1_tables")
    rows, views, manifest = C.load_frame()
    den = {v: len(views[v]) for v in VIEWS}
    log.info("denominators %s", den)
    flag_counts = Counter(r["meets_criteria_on_abstract"] for r in rows.values())
    log.info("flag counts in liberal frame %s", dict(flag_counts))
    metrics = {"denominators": den, "flag_counts_in_frame": dict(flag_counts)}
    hdr = ["item", "A_n", "A_pct", "B_n", "B_pct", "S_n", "S_pct"]
    den_row = ["N (denominator)", den["A"], "", den["B"], "", den["S"], ""]

    def emit(tag, title_note, csv_rows, tex_label_header="Item", extra_den=True):
        csv_rows_full = ([den_row] if extra_den else []) + csv_rows
        write_csv(RUN / f"{tag}.csv", hdr, csv_rows_full)
        body = []
        if extra_den:
            body.append(["N (denominator)", str(den["A"]), str(den["B"]), str(den["S"])])
            body.append(["\\midrule"])
        for r in csv_rows:
            if r[0] == "\\midrule":
                body.append(["\\midrule"])
                continue
            body.append([r[0]] + [fmt_np(r[1 + 2 * k], den[v]) if r[1 + 2 * k] != "" else "" for k, v in enumerate(VIEWS)])
        write_tex(TEX / f"{tag}.tex", title_note, [tex_label_header, "A: liberal frame, n (%)", "B: flagged yes, n (%)", "S: strict frame, n (%)"],
                  body, "lrrr")
        log.info("wrote %s (%d rows)", tag, len(csv_rows))

    # ---------------- T-RQ1a: paradigm families (any) ----------------
    fam_items = [(f"{f} {C.FAMILY_NAMES[f]}", (lambda r, f=f: any(p["family"] == f for p in r["paradigms"]))) for f in C.FAMILIES]
    fam_items.append(("None named", lambda r: not r["paradigms"]))
    ta = count_table("a", fam_items, None, rows, views, den)
    # order families by view A count (descending), None last
    ta_sorted = sorted(ta[:-1], key=lambda r: -r[1]) + [ta[-1]]
    emit("T-RQ1a", "Records with at least one paradigm of the family; records can have several families, columns do not sum to N.", ta_sorted, "Paradigm family")
    metrics["T-RQ1a"] = {r[0]: {"A": r[1], "B": r[3], "S": r[5]} for r in ta_sorted}

    # ---------------- T-RQ1b: model families + n_models_stated ----------------
    mf_items = [(m, (lambda r, m=m: m in r["model_families"])) for m in C.MODEL_FAMILIES]
    mf_items.append(("None named", lambda r: not r["model_families"]))
    tb = count_table("b", mf_items, None, rows, views, den)
    emit("T-RQ1b", "Records naming at least one model of the family (coder-assigned family list); columns do not sum to N.", tb, "Model family")
    # n_models_stated summary
    nm_rows = []
    for stat in ["n stated", "% of N stated", "median", "Q1", "Q3", "max"]:
        r = [stat]
        for v in VIEWS:
            xs = sorted(rows[i]["n_models_stated"] for i in views[v] if rows[i]["n_models_stated"] is not None)
            if stat == "n stated":
                val = len(xs)
            elif stat == "% of N stated":
                val = C.pct(len(xs), den[v])
            elif not xs:
                val = ""
            elif stat == "median":
                val = statistics.median(xs)
            elif stat == "max":
                val = max(xs)
            else:
                q = statistics.quantiles(xs, n=4, method="inclusive")
                val = q[0] if stat == "Q1" else q[2]
            r.append(val)
        nm_rows.append(r)
    write_csv(RUN / "T-RQ1b_n_models_stated.csv", ["statistic", "A", "B", "S"], nm_rows)
    write_tex(TEX / "T-RQ1b_n_models_stated.tex", "Among records where the abstract states the number of models; quartiles by the inclusive method.",
              ["Statistic", "A: liberal frame", "B: flagged yes", "S: strict frame"], [[str(c) for c in r] for r in nm_rows], "lrrr")
    metrics["T-RQ1b_n_models_stated"] = {r[0]: {"A": r[1], "B": r[2], "S": r[3]} for r in nm_rows}
    metrics["T-RQ1b"] = {r[0]: {"A": r[1], "B": r[3], "S": r[5]} for r in tb}

    # ---------------- T-RQ1c: languages, modality, human comparison, codable ----------------
    def lang_has(r, kind):
        ls = [x.lower() for x in r["languages"]]
        eng = any(x == "english" or x.endswith(" english") for x in ls)
        chi = any(("chinese" in x) or ("mandarin" in x) or ("cantonese" in x) for x in ls)
        oth = any(not (x == "english" or x.endswith(" english") or "chinese" in x or "mandarin" in x or "cantonese" in x) for x in ls)
        return {"en": eng, "zh": chi, "oth": oth, "none": not ls}[kind]

    tc = []
    tc += count_table("c1", [("Language: English (incl. varieties)", lambda r: lang_has(r, "en")),
                             ("Language: Chinese (incl. Mandarin, Cantonese)", lambda r: lang_has(r, "zh")),
                             ("Language: other named", lambda r: lang_has(r, "oth")),
                             ("Language: not stated", lambda r: lang_has(r, "none"))], None, rows, views, den)
    tc.append(["\\midrule"] + [""] * 6)
    tc += count_table("c2", [("Modality: text", lambda r: r["modality"] == "text"),
                             ("Modality: image+text", lambda r: r["modality"] == "image+text"),
                             ("Modality: not stated", lambda r: r["modality"] == "not_stated")], None, rows, views, den)
    tc.append(["\\midrule"] + [""] * 6)
    tc += count_table("c3", [("Human comparison: yes", lambda r: r["human_comparison"] == "yes"),
                             ("Human comparison: no", lambda r: r["human_comparison"] == "no"),
                             ("Human comparison: not stated", lambda r: r["human_comparison"] == "not_stated")], None, rows, views, den)
    tc.append(["\\midrule"] + [""] * 6)
    tc += count_table("c4", [("RQ1 codable (paradigm family and model named)", lambda r: bool(r["rq1_codable"]))], None, rows, views, den)
    # csv keeps a blank spacer row out: drop rule markers for csv
    tc_csv = [r for r in tc if r[0] != "\\midrule"]
    write_csv(RUN / "T-RQ1c.csv", hdr, [den_row] + tc_csv)
    body = [["N (denominator)", str(den["A"]), str(den["B"]), str(den["S"])], ["\\midrule"]]
    for r in tc:
        if r[0] == "\\midrule":
            body.append(["\\midrule"])
        else:
            body.append([r[0]] + [fmt_np(r[1 + 2 * k], den[v]) for k, v in enumerate(VIEWS)])
    write_tex(TEX / "T-RQ1c.tex", "Languages are record-level and non-exclusive except 'not stated'; modality and human comparison are exclusive.",
              ["Item", "A: liberal frame, n (%)", "B: flagged yes, n (%)", "S: strict frame, n (%)"], body, "lrrr")
    metrics["T-RQ1c"] = {r[0]: {"A": r[1], "B": r[3], "S": r[5]} for r in tc_csv}
    log.info("wrote T-RQ1c")
    lang_counter = Counter(l for i in views["A"] for l in rows[i]["languages"])
    metrics["languages_named_view_A_top"] = lang_counter.most_common(15)

    # ---------------- T-RQ1d: year x first family ----------------
    fam_cols = C.FAMILIES + ["none"]
    d_long = []
    wide = {}
    for v in VIEWS:
        yrs = sorted({rows[i]["year"] for i in views[v]})
        cnt = defaultdict(Counter)
        for i in views[v]:
            cnt[("year", rows[i]["year"])][C.first_family(rows[i])] += 1
            cnt[("period", C.period_of(rows[i]["year"]))][C.first_family(rows[i])] += 1
        wide[v] = cnt
        for (kind, key), c in sorted(cnt.items(), key=lambda kv: (kv[0][0], str(kv[0][1]))):
            for f in fam_cols:
                d_long.append([v, kind, key, f, c.get(f, 0)])
    write_csv(RUN / "T-RQ1d_long.csv", ["view", "bin_type", "bin", "first_family", "n"], d_long)
    # wide csv + tex
    d_wide_rows = []
    for v in VIEWS:
        for kind, keys in (("period", C.PERIODS), ("year", sorted({rows[i]["year"] for i in views["A"]}))):
            for key in keys:
                c = wide[v].get((kind, key), Counter())
                d_wide_rows.append([v, kind, key] + [c.get(f, 0) for f in fam_cols] + [sum(c.values())])
    write_csv(RUN / "T-RQ1d.csv", ["view", "bin_type", "bin"] + fam_cols + ["total"], d_wide_rows)
    for kind, fname, note in (("period", "T-RQ1d_periods", "Rows are periods of the sample design (2018-2023, 2024, 2025-2026); family = first family listed by the coder, 'none' = no paradigm named."),
                              ("year", "T-RQ1d_years", "Rows are publication years; 2026 is partial (search run 2026-10-16). Family = first family listed by the coder.")):
        body = []
        for v in VIEWS:
            body.append([f"\\multicolumn{{{len(fam_cols) + 2}}}{{l}}{{\\textit{{{tex_esc(C.VIEW_LABEL[v])} (N = {den[v]})}}}}"])
            keys = C.PERIODS if kind == "period" else sorted({rows[i]["year"] for i in views["A"]})
            for key in keys:
                c = wide[v].get((kind, key), Counter())
                body.append([str(key)] + [str(c.get(f, 0)) for f in fam_cols] + [str(sum(c.values()))])
            if v != VIEWS[-1]:
                body.append(["\\midrule"])
        write_tex(TEX / f"{fname}.tex", note, ["Bin"] + fam_cols + ["Total"], body, "l" + "r" * (len(fam_cols) + 1), resize=True)
    metrics["T-RQ1d_totals_by_period"] = {v: {p: sum(wide[v][("period", p)].values()) for p in C.PERIODS} for v in VIEWS}
    metrics["T-RQ1d_totals_by_year"] = {v: {str(y): sum(wide[v][("year", y)].values()) for y in sorted({rows[i]["year"] for i in views[v]})} for v in VIEWS}
    log.info("wrote T-RQ1d")

    # ---------------- T-RQ1e: top 25 paradigm names ----------------
    name_rec = {v: defaultdict(set) for v in VIEWS}
    name_fam = defaultdict(Counter)
    surface = defaultdict(Counter)
    for v in VIEWS:
        for i in views[v]:
            for p in rows[i]["paradigms"]:
                k = C.norm_name(p["name"])
                if not k:
                    continue
                name_rec[v][k].add(i)
                if v == "A":
                    name_fam[k][p["family"]] += 1
                    surface[k][p["name"]] += 1
    ranked = sorted(name_rec["A"].items(), key=lambda kv: (-len(kv[1]), kv[0]))
    n_names = len(ranked)
    n_once = sum(1 for _, s in ranked if len(s) == 1)
    top = ranked[:25]
    e_rows = []
    for rank, (k, s) in enumerate(top, 1):
        fc = name_fam[k].most_common()
        fam_str = fc[0][0] if len(fc) == 1 else "; ".join(f"{f} {n}" for f, n in fc)
        e_rows.append([rank, k, fam_str, len(s), C.pct(len(s), den["A"]), len(name_rec["B"].get(k, ())), len(name_rec["S"].get(k, ()))])
    ehdr = ["rank", "paradigm_name_normalised", "family_codes_in_A", "A_n_records", "A_pct", "B_n_records", "S_n_records"]
    write_csv(RUN / "T-RQ1e.csv", ehdr, e_rows)
    body = [[str(r[0]), r[1], r[2], fmt_np(r[3], den["A"]), str(r[5]), str(r[6])] for r in e_rows]
    write_tex(TEX / "T-RQ1e.tex", f"Normalised by lowercasing and stripping punctuation only (no semantic merging). Distinct normalised names in A: {n_names}, of which {n_once} occur once. Family column: codes assigned by the coder across occurrences in A (count when more than one).",
              ["Rank", "Paradigm name (normalised)", "Family", "A: n (%)", "B: n", "S: n"], body, "rllrrr")
    metrics["T-RQ1e"] = {"distinct_names_A": n_names, "names_once_A": n_once, "top25": [{"name": r[1], "family": r[2], "A": r[3], "B": r[5], "S": r[6]} for r in e_rows]}
    log.info("wrote T-RQ1e; distinct normalised names in A %d (%d once)", n_names, n_once)

    # ---------------- summary.md ----------------
    flag_lines = [l.rstrip() for l in FLAGFILE.read_text(encoding="utf-8").splitlines()
                  if l.startswith("- False") or l.startswith("- Reference") or l.startswith("Records used")]
    fam_first = {v: Counter(C.first_family(rows[i]) for i in views[v]) for v in VIEWS}
    s = []
    s.append("# RQ1 descriptive tables (runs/rq1-tables)\n")
    s.append(f"Generated by `analysis/rq1/rq1_tables.py`, config `runs/rq1-tables/config.json`. Evidence level E4 (computed here), on abstract-level codes.\n")
    s.append("## What these numbers are")
    s.append("RQ1 is **abstract-level coding by Claude Sonnet** (frozen brief `research/protocol/rq1-abstract-coding-brief.md`, "
             "blind to all screening labels), not full-text extraction. A paradigm, model or language is counted only when the title or abstract names it; "
             "an empty field means 'not named in the abstract', not 'absent from the study'.\n")
    s.append("## Views and denominators (protocol v0.9 item 2; neither view is the headline)")
    s.append(f"- **View A**: liberal frame, N = {den['A']} (abstract-decisions-v08, `liberal == eligible`).")
    s.append(f"- **View B**: coder-flagged subset of A, `meets_criteria_on_abstract == yes`, N = {den['B']}. "
             f"The flag distribution in A is yes {flag_counts['yes']}, unclear {flag_counts['unclear']}, no {flag_counts['no']}. "
             "(Amendment v0.9 reports 996 yes over all 2,032 coded records, which include the 10 pilot-only records outside the frame.)")
    s.append(f"- **Sensitivity S**: strict frame, N = {den['S']} (`strict == eligible`; all strict records are in A). Reported as a third column, all records of the strict frame regardless of the flag.")
    s.append("- Percentages use the view's N as the denominator, including for n_models_stated rows (\"% of N stated\"). Paradigm families, model families and languages are counted per record (at least one item), so those columns do not sum to N. T-RQ1d and Fig 2 use the first paradigm family listed by the coder (the sample-design rule, v0.9.1), so rows sum to the view total.\n")
    s.append("## Tables")
    s.append("| Table | Content | Denominator | Files |\n|---|---|---|---|")
    s.append(f"| T-RQ1a | Paradigm families, any listed (11 codes + none named) | A {den['A']} / B {den['B']} / S {den['S']} | `T-RQ1a.csv`, `paper/tables/T-RQ1a.tex` |")
    s.append(f"| T-RQ1b | Model families (GPT, Claude, Gemini, Llama, Mistral, Qwen, OLMo, other, none named); n_models_stated (n, median, IQR, max) | same; n_models_stated summarised over records that state a number | `T-RQ1b.csv`, `T-RQ1b_n_models_stated.csv`, tex |")
    s.append(f"| T-RQ1c | Languages (English, Chinese, other named, not stated), modality, human comparison, rq1_codable | same | `T-RQ1c.csv`, tex |")
    s.append(f"| T-RQ1d | Period (2018-2023, 2024, 2025-2026) and year x first family | same (rows sum to N) | `T-RQ1d.csv`, `T-RQ1d_long.csv`, `T-RQ1d_periods.tex`, `T-RQ1d_years.tex` |")
    s.append(f"| T-RQ1e | Top 25 normalised paradigm names (exact match after lowercasing and punctuation stripping; {n_names} distinct names in A, {n_once} once) | records in A, with B and S counts | `T-RQ1e.csv`, tex |\n")
    s.append("## Error estimates of the coder flag (quoted, not recomputed)")
    s.append(f"Source: `runs/fulltext-pilot/rq1-flag-crosstab.md` (sha256 `{C.sha256(FLAGFILE)[:16]}...`), amendment v0.9 item 3. Wilson 95 percent intervals as written in the source:\n")
    s += [l if l.startswith("-") else f"> {l}" for l in flag_lines]
    s.append("\nLimits stated in protocol v0.9: 53 usable records, which also chose the screening rule (partly post-selection); the flag is an additional measurement, not a gold standard, and was not tuned after the check. "
             "The false-exclusion rate of view B relative to view A is therefore uncertain (1/32 missed, interval 0.01 to 0.16), and 'unclear' (about a third of reference-YES and reference-NO alike) is not resolved by the abstract.\n")
    s.append("## Other caveats")
    s.append("- Years come from `records.jsonl` (`year`); 2026 is a partial year (search run 2026-10-16).")
    s.append("- Model-family and language assignments were made by the coder from the abstract; 'other' covers all families not on the fixed list (for example DeepSeek, Grok).")
    s.append("- T-RQ1e merges only exact matches after normalisation; near-synonymous names stay separate, so counts understate paradigm frequency.")
    (RUN / "summary.md").write_text("\n".join(s) + "\n", encoding="utf-8")
    metrics["first_family_counts"] = {v: dict(fam_first[v]) for v in VIEWS}
    (RUN / "metrics.json").write_text(json.dumps(metrics, indent=1, ensure_ascii=False), encoding="utf-8")

    inputs = C.code_files() + [C.P / "rq1/manifest.json", C.P / "screen/abstract-decisions-v08.jsonl", C.P / "records.jsonl", FLAGFILE,
                               Path(__file__).resolve(), Path(__file__).resolve().parent / "rq1_common.py"]
    C.write_config(RUN, "analysis/rq1/rq1_tables.py", inputs, {"views": {"A": "liberal==eligible", "B": "A and meets_criteria_on_abstract==yes", "S": "strict==eligible"},
                                                              "top_n_paradigms": 25}, {"denominators": den})
    log.info("done")


if __name__ == "__main__":
    main()
