# prompt identity
# ----------------------------------------------------------------------------------------------------------------------------
def armL_code(item, W, O, x, PA, common):
    p = PA.build(item, W, x, O, F="F0", common=common)
    return sha(canon(p["system"], p["turns"]))


def armS_code(item, W, O, x, PA, common, RP, pcommon, pwords):
    if item in NEW:
        p = PA.build(item, W, x, O, F="F0", common=common)   # run_armS.py: PA.build(item, W, x, O, F=st["F"]) with F0
        return sha(canon(p["system"], p["turns"]))
    p = RP.build_prompt(pcommon, pwords, item, W, "F0", x, O)   # run_pilot.py
    return sha(canon(p["system"], [("user", p["user"])]))


def armL_disk(runs, models):
    """{(item, W, O, x): set of prompt hashes} over all Arm L rows of variant main, W0-W3."""
    out = {}
    for m in models:
        for it in ITEMS:
            f = runs / "acme-L" / m / f"{it}.jsonl"
            if not f.exists():
                continue
            with f.open(encoding="utf8") as fh:
                for line in fh:
                    if '"variant": "main"' not in line:
                        continue
                    r = json.loads(line)
                    if r["variant"] != "main" or r["W"] not in WS:
                        continue
                    out.setdefault((it, r["W"], r["O"], r["x"]), set()).add(sha(canon(r["system"], r["turns"])))
    return out


def armS_disk(runs, models):
    """Pilot items only (rows store system and user): {(item, W, O, x): set of prompt hashes}, F0 rows (all temperatures, greedy included)."""
    import gate_g4 as g4
    out = {}
    for m in models:
        for it in g4.PILOT:
            f = g4.source(runs, m, it)
            if not f.exists():
                continue
            with f.open(encoding="utf8") as fh:
                for line in fh:
                    r = json.loads(line)
                    if r.get("F") != "F0" or r["W"] not in WS:
                        continue
                    out.setdefault((it, r["W"], r.get("O"), r["x"]), set()).add(sha(canon(r["system"], [("user", r["user"])])))
    return out


def prompt_identity():
    import importlib.util
    import prompts_acme as PA
    import run_pilot as RP

    def load(name, path):
        spec = importlib.util.spec_from_file_location(name, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod
    PM_acme = load("acme_prompt_manifest", HERE / "prompt_manifest.py")
    PM_pilot = load("pilot_prompt_manifest", ROOT / "analysis/pilot/prompt_manifest.py")
    bad_acme, bad_pilot = PM_acme.verify(), PM_pilot.verify()
    common = PA.load_common()
    pcommon, pwords = RP.load_prompts()
    runs = ROOT / "runs"
    models = sorted(p.name for p in (runs / "acme-S").iterdir() if p.is_dir())
    dl, ds = armL_disk(runs, models), armS_disk(runs, models)
    rows = []
    for it in ITEMS:
        for W in WS:
            for OL in ORDERS_L.get(it, [None]):
                for x in (1, 0):
                    OS = None if it == "P3" else OL
                    has_s = not (it == "P3" and OL == "reversed")
                    hl = armL_code(it, W, OL, x, PA, common)
                    hs = armS_code(it, W, OS, x, PA, common, RP, pcommon, pwords) if has_s else ""
                    dL = dl.get((it, W, OL, x), set())
                    dS = ds.get((it, W, OS, x), set()) if it not in NEW else None
                    rows.append(dict(item=it, W=W, O_armL="" if OL is None else OL, O_armS=("" if OS is None else OS) if has_s else "",
                                     x=x, sha_armL=hl, sha_armS=hs,
                                     match=("n/a (no Arm S counterpart)" if not has_s else str(hl == hs)),
                                     armL_disk_n_distinct=len(dL), armL_disk_equals_code=str(dL == {hl}),
                                     armS_source=("rebuild via prompts_acme.build (rows do not store the prompt)" if it in NEW
                                                  else "rows on disk + rebuild via run_pilot.build_prompt") if has_s else "",
                                     armS_disk_n_distinct=("" if dS is None or not has_s else len(dS)),
                                     armS_disk_equals_code=("" if dS is None or not has_s else str(dS == {hs}))))
    det = pd.DataFrame(rows)
    agg = []
    for (it, W), g in det.groupby(["item", "W"], sort=False):
        g2 = g[g["match"] != "n/a (no Arm S counterpart)"]
        agg.append(dict(item=it, W=W, n_prompts_compared=len(g2),
                        sha256_armL=sha(sorted([r.O_armL, r.x, r.sha_armL] for r in g2.itertuples())),
                        sha256_armS=sha(sorted([r.O_armL, r.x, r.sha_armS] for r in g2.itertuples())),
                        match=str(bool((g2["match"] == "True").all())),
                        n_prompts_without_armS_counterpart=int((g["match"] == "n/a (no Arm S counterpart)").sum()),
                        armL_disk_equals_code=str(bool((g["armL_disk_equals_code"] == "True").all())),
                        armS_disk_equals_code=("n/a (rows do not store the prompt)" if it in NEW
                                               else str(bool((g2["armS_disk_equals_code"] == "True").all())))))
    prov = dict(acme_manifest_mismatch=bad_acme, pilot_manifest_mismatch=bad_pilot, arm_s_models=models,
                note="sha256 = SHA-256 of json.dumps([system, [[role, text], ...]], ensure_ascii=False, sort_keys=True) in UTF-8; the per-(item, W) "
                     "hash covers the sorted list of [order, x, prompt hash] over the compared prompts (Arm S has no P3 order: its P3 is compared with "
                     "Arm L 'forward')")
    return pd.DataFrame(agg), det, prov


# ----------------------------------------------------------------------------------------------------------------------------
def main():
    ros = intersection()
    n_left = ros[ros["ok"]].groupby("item").size().reindex(ITEMS, fill_value=0).astype(int).to_dict()
    keep = [i for i in ITEMS if n_left[i] >= MIN_MODELS]
    OUT_S.mkdir(parents=True, exist_ok=True)
    ros.to_csv(OUT_S / "roster_intersection.csv", index=False)
    eff = pd.read_csv(EFF, dtype={"W": str, "O": str, "model": str, "item": str, "variant": str})
    ok = set(zip(ros[ros["ok"]]["model"], ros[ros["ok"]]["item"]))
    sel = eff[(eff["variant"] == "main") & eff["W"].isin(WS) & eff["T"].isin(TS) & eff["item"].isin(keep)
              & pd.Series([(m, i) in ok for m, i in zip(eff["model"], eff["item"])], index=eff.index)]
    # E7b item 1: P3 in (e) uses Arm L's 'forward' prompts only, the order Arm S used; 'reversed' P3 stays in column (b).
    sel = sel[~((sel["item"] == "P3") & (sel["O"] != "forward"))]
    inp = OUT_L / "inputs"
    inp.mkdir(parents=True, exist_ok=True)
    sel.to_csv(inp / "effects.csv", index=False)
    (inp / "roster.json").write_text(json.dumps(dict(
        rule="ok in runs/acme-S-gstudy/roster_strict.csv AND not in runs/acme-L/exclusions_per_type.csv", min_models=MIN_MODELS,
        models_left=n_left, decomposed=keep, not_decomposed={k: v for k, v in n_left.items() if k not in keep},
        wordings=list(WS), temps=list(TS), variant="main",
        models={i: sorted(ros[(ros["item"] == i) & ros["ok"]]["model"]) for i in keep}), indent=1))
    print("intersection models left:", n_left, "| decomposed:", keep)
    agg, det, prov = prompt_identity()
    agg.to_csv(OUT_L / "prompt_identity.csv", index=False)
    det.to_csv(OUT_L / "prompt_identity_detail.csv", index=False)
    prov["git_head"] = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    (OUT_L / "prompt_identity.json").write_text(json.dumps(prov, indent=1), encoding="utf8")
    mism = agg[agg["match"] != "True"]
    print("prompt identity: (item, W) groups", len(agg), "| mismatches:", len(mism))
    if len(mism):
        print(mism[["item", "W", "match"]].to_string(index=False))
    print("manifest mismatches: acme", prov["acme_manifest_mismatch"], "pilot", prov["pilot_manifest_mismatch"])


if __name__ == "__main__":
    main()
