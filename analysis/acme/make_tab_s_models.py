"""Generate paper/acme/tables/tab-s-models.tex (Supplement Table: model roster with the valid-mass check and the near-deterministic share).

One row per roster model: precision, the items removed by the valid-mass rule (runs/acme-L/outcomes/valid_mass.csv, the rule of
gate G3: valid mass below the threshold on more than the allowed share of prompts), and the share of near-deterministic prompts
on the three binary items P1, AF and NR (make_autonumbers.nd_shares: maximum option probability above 0.99, main variant, four
temperatures). The share is a property of the prompts that a model answers, not a quality rating.

Usage:  python analysis/acme/make_tab_s_models.py [--out paper/acme/tables/tab-s-models.tex]
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402  (records the files read, for the .source.json)
_REC = rc.record_reads()
from make_autonumbers import NUMBERS, ND_ITEMS, nd_shares, roster  # noqa: E402

PREC = {"bf16": "bf16", "nf4_saved": "NF4"}
ITEM_ORDER = ["P1", "AF", "NR", "P3", "QA", "P2a", "P2b", "P2c", "P2d", "P4"]


def build() -> str:
    main = [r for r in roster() if r["control"] == "false"]
    assert str(len(main)) == NUMBERS["n.models"].value
    excl: dict[str, list[str]] = {}
    with (ROOT / "runs/acme-L/outcomes/valid_mass.csv").open(encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["excluded"] == "True":
                excl.setdefault(r["model"], []).append(r["item"])
    nd = nd_shares()
    lines = [
        "% GENERATED by analysis/acme/make_tab_s_models.py from analysis/acme/models.yaml, runs/acme-L/outcomes/valid_mass.csv and runs/acme-L/outcomes/outcomes.csv.",
        "% Do not edit by hand; rerun the script. Share: near-deterministic prompts (maximum option probability above 0.99) of the binary items, in percent.",
        r"{\footnotesize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.05}",
        r"\begin{tabular}{@{}llrp{5.6cm}rrr@{}}",
        r"\toprule",
        r"Model & Precision & Items removed & Items removed by the valid-mass rule & P1 & AF & NR \\",
        r"\midrule",
    ]
    for r in main:
        slug = r["slug"]
        items = sorted(excl.get(slug, []), key=ITEM_ORDER.index)
        cells = []
        for it in ND_ITEMS:
            k, n = nd[(slug, it)]
            cells.append(f"{100 * k / n:.0f}")
        lines.append(f"{r['repo'].split('/', 1)[1]} & {PREC[r['quant']]} & {len(items)} & {', '.join(items) if items else 'none'} & "
                     + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "paper" / "acme" / "tables" / "tab-s-models.tex")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(), encoding="utf-8", newline="\n")
    rc.write_source_recorded([args.out], "analysis/acme/make_tab_s_models.py", _REC)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
