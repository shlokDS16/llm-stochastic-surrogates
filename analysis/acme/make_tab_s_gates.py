"""Generate the supplement gate tables tab-s-g1.tex (gate G1 in full) and tab-s-g1b.tex (gate G1b in full).

Gate G1 (runs/acme-G1/results.csv for the estimator as first written, results_A1.csv for amendment A-G1): for each of the nine
synthetic scenarios and each variance component at the pooled level, the true share, the bias of the mean estimate, the coverage
of the 95 percent interval and the rate at which the lower bound lies above zero. Gate G1b (runs/acme-G1b/results_H*_{null,alt}.csv):
for each boundary null and alternative, the replicates, the rejections at p < 0.05, the rate with an exact 95 percent interval and
the mean of the estimated quantity. Rejection counts are asserted equal to those behind Table verification and the \\NUM keys.

Usage:  python analysis/acme/make_tab_s_gates.py [--outdir paper/acme/tables]
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402  (records the files read, for the .source.json)
_REC = rc.record_reads()
from make_autonumbers import S7PRE_RAW, _cp_interval, _fx  # noqa: E402

COMP = ["M", "O", "MO", "W", "MW", "WO", "res"]
COMP_TEX = {"M": "M", "O": "O", "MO": r"M$\times$O", "W": "W", "MW": r"M$\times$W", "WO": r"W$\times$O", "res": "Residual"}


def _rows(rel: str) -> list[dict[str, str]]:
    with (ROOT / rel).open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _sg(x: float, nd: int = 3) -> str:
    s = f"{abs(x) if round(x, nd) == 0 else x:.{nd}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s


def build_g1() -> str:
    first = [r for r in _rows("runs/acme-G1/results.csv") if r["level"] == "pooled_mean"]
    amend = [r for r in _rows("runs/acme-G1/results_A1.csv") if r["level"] == "pooled_mean"]
    assert len(first) == len(amend) == 63
    key = lambda r: (r["scenario"], r["component"])  # noqa: E731
    fa, aa = {key(r): r for r in first}, {key(r): r for r in amend}
    assert set(fa) == set(aa)
    # reconcile with the pooled-level count behind Table verification: components with coverage in range
    g1 = S7PRE_RAW["g1"]
    lo, hi = float(g1["crit"]["lo"]), float(g1["crit"]["hi"])
    in_range = sum(lo <= float(r["coverage"]) <= hi for r in amend)
    assert in_range == g1["a"]["cov"], (in_range, g1["a"]["cov"])
    assert sum(lo <= float(r["coverage"]) <= hi for r in first) == g1["first"]["cov"]
    scen: list[tuple[str, str]] = []
    for r in amend:
        if (r["scenario"], r["scenario_label"]) not in scen:
            scen.append((r["scenario"], r["scenario_label"]))
    lines = [
        "% GENERATED by analysis/acme/make_tab_s_gates.py from runs/acme-G1/results.csv and results_A1.csv (pooled level). Do not edit by hand.",
        r"% Body rows of a longtable (caption, label and header: \TabSGone in floats.tex). Bias = mean estimate minus true share; Lower = rate at which the lower bound of the interval lies above zero.",
    ]
    for sc, label in scen:
        r0 = aa[(sc, "M")]
        label = label.replace("%", r"\%")
        lines.append(rf"\multicolumn{{8}}{{@{{}}l}}{{\textbf{{Scenario {sc.upper()}: {label}}} ({r0['reps']} replicates, {r0['B']} bootstrap draws)}} \\")
        for c in COMP:
            f, a = fa[(sc, c)], aa[(sc, c)]
            lines.append(f"{COMP_TEX[c]} & {_fx(a['true_share'], 2)} & {_sg(float(f['bias']))} & {_fx(f['coverage'], 3)} & {_fx(f['lower_gt0_rate'], 3)} & "
                         f"{_sg(float(a['bias']))} & {_fx(a['coverage'], 3)} & {_fx(a['lower_gt0_rate'], 3)} \\\\")
        lines.append(r"\addlinespace[2pt]")
    return "\n".join(lines) + "\n"


def _mean(rows: list[dict[str, str]], col: str) -> float:
    v = [float(r[col]) for r in rows if r[col] not in ("", "nan")]
    return sum(v) / len(v)


def build_g1b() -> str:
    R = S7PRE_RAW["g1b"]["rates"]
    spec = [
        ("H1", "null", "p_H1", "wording minus temperature share", "est_H1", "wording_H1", "T_H1"),
        ("H1", "alt", "p_H1", "wording minus temperature share", "est_H1", "wording_H1", "T_H1"),
        ("H2", "null", "p_H2", "median set-up SD, mean over items", "H2_mean_median_sd", None, None),
        ("H2", "alt", "p_H2", "median set-up SD, mean over items", "H2_mean_median_sd", None, None),
        ("H3", "null", "p_H3", r"M$\times$W minus W share", "est_H3", "MW_H3", "W_H3"),
        ("H3", "alt", "p_H3", r"M$\times$W minus W share", "est_H3", "MW_H3", "W_H3"),
    ]
    lines = [
        "% GENERATED by analysis/acme/make_tab_s_gates.py from runs/acme-G1b/results_H*_null.csv and results_H*_alt.csv. Do not edit by hand.",
        r"% Rejection: raw p below 0.05. Rate with an exact (Clopper-Pearson) 95 percent interval. Means are over replicates.",
        r"{\footnotesize\setlength{\tabcolsep}{2.5pt}\renewcommand{\arraystretch}{1.08}",
        r"\begin{tabular}{@{}llrr>{\raggedright\arraybackslash}p{3.1cm}>{\raggedright\arraybackslash}p{3.4cm}r>{\raggedright\arraybackslash}p{1.9cm}@{}}",
        r"\toprule",
        r"Test & Scenario & Replicates & Rejections & Rate (95 percent interval) & Estimated quantity & Mean & Mean shares (a / b) \\",
        r"\midrule",
    ]
    for h, kind, pcol, qty, ecol, a, b in spec:
        rows = _rows(f"runs/acme-G1b/results_{h}_{kind}.csv")
        ps = [float(r[pcol]) for r in rows if r[pcol] not in ("", "nan")]
        n, k = len(ps), sum(p < 0.05 for p in ps)
        ref = (R[h]["k"], R[h]["n"]) if kind == "null" else (R[h]["ka"], R[h]["na"])
        assert (k, n) == ref, (h, kind, (k, n), ref)
        lo, hi = _cp_interval(k, n)
        shares = f"{_fx(_mean(rows, a), 3)} / {_fx(_mean(rows, b), 3)}" if a else "n.a."
        lines.append(f"{h} & {'boundary null' if kind == 'null' else 'alternative'} & {n} & {k} & {_fx(k / n, 3)} ({_fx(lo, 3)} to {_fx(hi, 3)}) & "
                     f"{qty} & {_sg(_mean(rows, ecol))} & {shares} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--outdir", type=Path, default=ROOT / "paper" / "acme" / "tables")
    args = ap.parse_args()
    args.outdir.mkdir(parents=True, exist_ok=True)
    for name, text in (("tab-s-g1.tex", build_g1()), ("tab-s-g1b.tex", build_g1b())):
        (args.outdir / name).write_text(text, encoding="utf-8", newline="\n")
        rc.write_source_recorded([args.outdir / name], "analysis/acme/make_tab_s_gates.py", _REC)
        print(f"wrote {args.outdir / name}")


if __name__ == "__main__":
    main()
