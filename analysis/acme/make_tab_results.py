"""Generate paper/acme/tables/tab-results.tex (Table 8: variance shares of the simulation uncertainty and the hypotheses H1 to H3).

Every cell is computed from the files of a gstudy.py run directory; no number is typed here (formatting uses make_autonumbers._fx and _sg).
Blocks:
  A  per-item and pooled shares of the effect variance, one row per item and a pooled row, one column per component (stacked cell:
     share over its 95 percent interval), plus the number of models in each item's array.
     Source: components_by_item.csv (analysis T1) and pooled_shares.csv (analysis T1_3facet, stat mean).
  B  pooled shares by version (only when --alt is given): primary run and every --alt run side by side, equal billing (blueprint M3).
  C  H1, H2, H3 per version: estimate (interval), raw p, Holm p, decision.  Source: hypotheses.json.
M3 asks for a frozen, a logit-scale and a non-saturated version.  gstudy.py yields ONE estimator per effects table; the logit-scale (S4) and
non-saturated versions need gstudy.py runs on other effects tables, which this script does not make.  Give each such run as
    --alt "logit scale=runs/acme-gstudy/A1-logit" --alt "non-saturated cells=runs/acme-gstudy/A1-nonsat"
and name the primary with --label (default: the estimator named in summary.json).  Without --alt only the primary version is shown.

    .venv/Scripts/python.exe -I analysis/acme/make_tab_results.py [--gstudy runs/acme-gstudy/A1] [--out paper/acme/tables/tab-results.tex]
Writes OUT and OUT.source.json.  A scratch or synthetic --gstudy requires an explicit --out outside paper/.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402
from make_autonumbers import _fx  # noqa: E402  (importing runs the reconciliation of the number blocks; _sg is the same minus rule, see num)

HEAD = {"M": "M", "O": "O", "MO": r"M$\times$O", "W": "W", "MW": r"M$\times$W", "WO": r"W$\times$O", "res": "Resid."}


def tx(s: str) -> str:
    return s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")


def num(x: float, nd: int = 2) -> str:
    s = _fx(x, nd)
    if float(s) == 0.0:          # a negative value that rounds to zero is printed without a sign
        s = s.lstrip("-")
    return f"$-{s[1:]}$" if s.startswith("-") else s


def est_int(est: float, lo: float, hi: float, nd: int = 2) -> str:
    return f"{num(est, nd)} ({num(lo, nd)}, {num(hi, nd)})"


def pstr(p, B: int) -> str:
    if p is None:
        return "n/a"
    p = float(p)
    return f"$<${1.0 / B:g}" if p <= 0 else _fx(p, 3)


def load_version(tr: rc.Tracker, d: Path, label: str) -> dict:
    d = Path(d)
    summ = tr.json(d / "summary.json")
    return dict(label=label, dir=d, summ=summ, info=rc.estimator_info(summ), hyp=tr.json(d / "hypotheses.json"),
                comp=tr.csv(d / "components_by_item.csv", dtype={"item": str, "component": str}),
                pool=tr.csv(d / "pooled_shares.csv", dtype={"component": str}))


def hyp_rows(v: dict) -> list[tuple[str, str, str, str, str]]:
    h, B = v["hyp"], v["info"]["B"]
    rows = []

    def tail(x):
        return pstr(x.get("p_raw"), B), pstr(x.get("p_holm"), B), ("reject $H_0$" if x.get("reject_holm_alpha") else "retain $H_0$") if x.get("p_raw") is not None else "n/a"
    x = h["H1"]
    if x.get("p_raw") is None:
        rows.append(("H1", ("n/a (no four-facet arrays)", ""), "n/a", "n/a", "n/a"))
    else:
        rows.append(("H1", (est_int(x['estimate'], x['lo'], x['hi']), f"wording {num(x['pooled_wording'])}, temperature {num(x['pooled_T'])}"), *tail(x)))
    x = h["H2"]
    if x.get("p_raw") is None:
        rows.append(("H2", ("n/a (no single-site SE)", ""), "n/a", "n/a", "n/a"))
    else:
        import numpy as np
        ms = np.median([r["median_setup_sd"] for r in x["items"]])
        mc = np.median([r["single_site_se"] for r in x["items"]])
        rows.append(("H2", (f"{x['n_hold']} of {x['k']} items hold (need {x['need']})", f"median $s$ {num(ms)}, median $c$ {num(mc)}"), *tail(x)))
    x = h["H3"]
    rows.append(("H3", (est_int(x['estimate'], x['lo'], x['hi']), rf"M$\times$W {num(x['pooled_MW'])}, W {num(x['pooled_W'])}"), *tail(x)))
    return rows


def build(prim: dict, alts: list[dict]) -> str:
    comp, pool = prim["comp"], prim["pool"]
    comp = comp[comp["analysis"] == "T1"]
    pool = pool[(pool["analysis"] == "T1_3facet") & (pool["stat"] == "mean")].set_index("component")
    cols = [c for c in rc.COMP_ORDER if c in set(comp["component"]) | set(pool.index)]
    tr = prim["_tr"]
    items = rc.items_in_order(tr, sorted(comp["item"].unique()))
    info = prim["info"]
    ival = rc.interval_word(info)
    L = [
        f"% GENERATED by analysis/acme/make_tab_results.py from {rc.rel(prim['dir'])}/ (components_by_item.csv, pooled_shares.csv, hypotheses.json, summary.json).",
        "% Do not edit by hand; rerun the script. Every cell is read from those files; <outfile>.source.json lists the SHA-256 of each input.",
        rf"{{\footnotesize\setlength{{\tabcolsep}}{{3pt}}\renewcommand{{\arraystretch}}{{1.0}}",
        r"\begin{tabular}{@{}l r " + "c" * len(cols) + r"@{}}", r"\toprule",
        r"Item & Models & " + " & ".join(HEAD[c] for c in cols) + r" \\", r"\midrule",
    ]
    two = {i for i in items if "O" in set(comp[comp["item"] == i]["component"])}
    def two_line(label, models, pairs):
        """Estimates on one table row, intervals on the next (scriptsize); `pairs` is a list of (estimate string, interval string)."""
        L.append(f"{label} & {models} & " + " & ".join(e for e, _ in pairs) + r" \\[-3pt]")
        L.append(r" & & " + " & ".join(rf"{{\scriptsize {i}}}" if i else "" for _, i in pairs) + r" \\[3pt]")

    for it in items:
        sub = comp[comp["item"] == it].set_index("component")
        pairs = []
        for c in cols:
            if c in sub.index:
                r = sub.loc[c]
                pairs.append((num(r["share"]) + (r"$^{\ddagger}$" if c == "MW" and it not in two else ""), f"({num(r['share_lo'])}, {num(r['share_hi'])})"))
            else:
                pairs.append(("--", ""))
        two_line(it, int(sub["n_models"].iloc[0]), pairs)
    L.append(r"\midrule")
    pairs = [(rf"\textbf{{{num(pool.loc[c, 'estimate'])}}}", f"({num(pool.loc[c, 'lo'])}, {num(pool.loc[c, 'hi'])})") if c in pool.index else ("--", "") for c in cols]
    two_line(r"\textbf{Pooled}", "", pairs)
    notes = [rf"Shares of the variance of the effect, mean over items for the pooled row; 95 percent {ival} intervals (estimator {tx(info['name'])}, "
             rf"B = {info['B']}, {info['share_mode']} components). $^{{\ddagger}}$ one-order item: the M$\times$W term holds the residual. A dash marks a term absent from the item's design."]
    left_out = [e for e in prim["summ"].get("exclusions", []) if "reason" in e and "item" in e]
    if left_out:
        notes.append("Left out of the shares: " + "; ".join(f"{tx(str(e['item']))} ({tx(str(e['reason']))})" for e in left_out) + ".")
    L += [r"\bottomrule", r"\end{tabular}}", r"\par\smallskip", r"{\scriptsize\raggedright " + " ".join(notes) + r"\par}"]

    versions = [prim] + alts
    if alts:
        L += [r"\par\medskip", r"{\footnotesize\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.10}",
              r"\begin{tabular}{@{}l " + "c" * len(versions) + r"@{}}", r"\toprule",
              r"Pooled share & " + " & ".join(tx(v["label"]) for v in versions) + r" \\", r"\midrule"]
        allc = [c for c in rc.COMP_ORDER if any(c in set(v["pool"][(v["pool"]["analysis"] == "T1_3facet") & (v["pool"]["stat"] == "mean")]["component"]) for v in versions)]
        for c in allc:
            cells = []
            for v in versions:
                p = v["pool"][(v["pool"]["analysis"] == "T1_3facet") & (v["pool"]["stat"] == "mean")].set_index("component")
                cells.append(est_int(p.loc[c, "estimate"], p.loc[c, "lo"], p.loc[c, "hi"]) if c in p.index else "--")
            L.append(HEAD[c] + " & " + " & ".join(cells) + r" \\")
        L += [r"\bottomrule", r"\end{tabular}}"]

    L += [r"\par\medskip", r"{\footnotesize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.0}",
          r"\begin{tabular}{@{}l l l r r l@{}}", r"\toprule",
          r"Version & Hypothesis & Estimate (95 percent interval) & $p$ & $p$ Holm & Decision \\", r"\midrule"]
    for n, v in enumerate(versions):
        for k, (h, (e, detail), p, ph, dec) in enumerate(hyp_rows(v)):
            L.append(f"{tx(v['label']) if k == 0 else ''} & {h} & {e} & {p} & {ph} & {dec} " + r"\\[-1pt]")
            L.append(r" & & {\scriptsize " + detail + r"} & & & \\[3pt]")
        if n < len(versions) - 1:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}}", r"\par\smallskip",
          r"{\scriptsize\raggedright H1: wording share (W and M$\times$W) minus the temperature share, one-sided. H2: items whose lower interval bound of the "
          r"median set-up SD $s$ exceeds the single-site SE $c$; the $p$-value is the intersection-union value over items. H3: M$\times$W share minus W share, two-sided. "
          r"Holm adjustment over the three hypotheses.\par}"]
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--gstudy", default=str(rc.DEFAULT_GSTUDY))
    ap.add_argument("--label", default=None, help="name of the primary version (default: the estimator in summary.json)")
    ap.add_argument("--alt", action="append", default=[], metavar="LABEL=DIR", help="further gstudy run to show with equal billing (blueprint M3)")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    gs = rc.resolve_arg(a.gstudy)
    alt_dirs = []
    for s in a.alt:
        if "=" not in s:
            raise SystemExit(f"--alt needs LABEL=DIR, got {s!r}")
        lab, d = s.split("=", 1)
        alt_dirs.append((lab.strip(), rc.resolve_arg(d.strip())))
    out = rc.resolve_arg(a.out, rc.ROOT / "paper" / "acme" / "tables" / "tab-results.tex")
    rc.guard([out], a.out is not None, gs, model_inputs=[d for _, d in alt_dirs])
    tr = rc.Tracker()
    prim = load_version(tr, gs, a.label or "")
    prim["label"] = a.label or f"estimator {prim['info']['name']}"
    prim["_tr"] = tr
    alts = [load_version(tr, d, lab) for lab, d in alt_dirs]
    text = build(prim, alts)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    rc.write_source([out], "analysis/acme/make_tab_results.py", gs, tr, extra=dict(versions=[prim["label"]] + [v["label"] for v in alts],
                                                                                 alt_dirs=[rc.rel(d) for _, d in alt_dirs]))


if __name__ == "__main__":
    main()
