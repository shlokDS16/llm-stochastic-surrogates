"""Generate paper/acme/tables/tab-verification.tex (estimator verification on synthetic ground truth, Table 9 of the blueprint).

Gate G1 (runs/acme-G1/results.csv for the estimator as first written, results_A1.csv for amendment A-G1): four criteria at the pooled
level, with the preregistered targets. Gate G1b (runs/acme-G1b/VERDICT.md tables, reconciled with results_H*_null.csv and
results_H*_alt.csv): rejection rate of each preregistered test at its boundary null, and power against one alternative per hypothesis
(information only), with exact (Clopper-Pearson) 95 percent intervals for the rates. Generated tables only: the hand-written reading
notes of the G1b verdict are not used. All values come from make_autonumbers._section7pre_numbers (S7PRE_RAW), which reconciles them
with the rendered verdict tables, so the table and the \\NUM keys of the text cannot disagree.

Usage:  python analysis/acme/make_tab_verification.py [--out paper/acme/tables/tab-verification.tex]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402  (records the files read, for the .source.json)
_REC = rc.record_reads()
from make_autonumbers import NUMBERS, S7PRE_RAW, _cp_interval, _fx, _read, _rx  # noqa: E402


def rate_cell(k: int, n: int) -> str:
    lo, hi = _cp_interval(k, n)
    return f"{k}/{n} = {_fx(k / n, 3)} ({_fx(lo, 3)} to {_fx(hi, 3)})"


def build() -> str:
    g1, g1b = S7PRE_RAW["g1"], S7PRE_RAW["g1b"]
    f, a, c, need, nc = g1["first"], g1["a"], g1["crit"], g1["need"], g1["a"]["n"]
    pre = _read("research/relaunch/PREREG-acme.md")
    alt = _rx(pre, r"H1 wording (0\.40) vs T (0\.10); H3 M×W\s+(0\.45) vs W (0\.15); H2 true s_p = 2c_p", "G1b alternatives")
    p_h1, p_h1t, p_h3, p_h3w = alt.group(1), alt.group(2), alt.group(3), alt.group(4)
    mark = lambda ok: "pass" if ok else "fail"  # noqa: E731
    ok = lambda tag, cond: mark(cond)  # noqa: E731
    bias_ok = lambda x: x <= float(c["bias"])  # noqa: E731
    rows = [
        ("G1", "Largest absolute bias of a pooled share", f"at most {c['bias']}",
         f"{_fx(f['bias'], 3)} ({ok('', bias_ok(f['bias']))})", f"{_fx(a['bias'], 3)} ({ok('', bias_ok(a['bias']))})"),
        ("G1", f"Components with 95 percent coverage in {c['lo']} to {c['hi']} (of {nc})", f"at least {need}",
         f"{f['cov']} ({ok('', f['cov'] >= need)})", f"{a['cov']} ({ok('', a['cov'] >= need)})"),
        ("G1", f"Largest rate of a lower bound above zero for a zero component ({g1['a']['nzero']} components)", f"at most {c['fp']}",
         f"{_fx(f['fp'], 2)} ({ok('', f['fp'] <= float(c['fp']))})", f"{_fx(a['fp'], 3)} ({ok('', a['fp'] <= float(c['fp']))})"),
        ("G1", "Lowest rate at which the largest component ranks first", f"at least {int(c['rank']) / 100:.2f}",
         f"{_fx(f['rank'], 3)} ({ok('', f['rank'] >= int(c['rank']) / 100)})", f"{_fx(a['rank'], 3)} ({ok('', a['rank'] >= int(c['rank']) / 100)})"),
    ]
    R = g1b["rates"]
    lim = _fx(g1b["lim"], 4)
    null_rows = [
        ("G1b", "H1 rejection rate, wording share equal to temperature share", "H1"),
        ("G1b", "H2 rejection rate, every set-up SD equal to the single-site SE", "H2"),
        ("G1b", "H3 rejection rate, M$\\times$W share equal to W share", "H3"),
    ]
    alt_rows = [
        ("G1b", f"H1 power, wording share {p_h1} against temperature share {p_h1t}", "H1"),
        ("G1b", f"H2 power, set-up SD twice the single-site SE", "H2"),
        ("G1b", f"H3 power, M$\\times$W share {p_h3} against W share {p_h3w}", "H3"),
    ]
    lines = [
        "% GENERATED by analysis/acme/make_tab_verification.py from runs/acme-G1/results*.csv and runs/acme-G1b/ (VERDICT.md tables, result CSVs).",
        "% Do not edit by hand; rerun the script. G1: pooled level; estimator as first written against amendment A-G1.",
        "% G1b: rate = rejections/replicates with an exact 95 percent interval; power is information only.",
        r"{\footnotesize\setlength{\tabcolsep}{4pt}\renewcommand{\arraystretch}{1.08}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.06\textwidth}>{\raggedright\arraybackslash}p{0.38\textwidth}"
        r">{\raggedright\arraybackslash}p{0.12\textwidth}>{\raggedright\arraybackslash}p{0.16\textwidth}>{\raggedright\arraybackslash}p{0.18\textwidth}@{}}",
        r"\toprule",
        r"Gate & Quantity & Target & As first written & Amendment A-G1 \\",
        r"\midrule",
    ]
    for g, q, t, x, y in rows:
        lines.append(f"{g} & {q} & {t} & {x} & {y} \\\\")
    lines.append(r"\addlinespace[2pt]")
    for g, q, h in null_rows:
        k, n = R[h]["k"], R[h]["n"]
        assert R[h]["rate"] <= g1b["lim"]
        lines.append(f"{g} & {q} & at most {lim} & \\multicolumn{{2}}{{l}}{{{rate_cell(k, n)}}} \\\\")
    for g, q, h in alt_rows:
        k, n = R[h]["ka"], R[h]["na"]
        lines.append(f"{g} & {q} & information only & \\multicolumn{{2}}{{l}}{{{rate_cell(k, n)}}} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    # reconcile with the text keys
    assert NUMBERS["bm.g1.a.cov"].value == str(a["cov"]) and NUMBERS["bm.g1.first.cov"].value == str(f["cov"])
    assert NUMBERS["bm.g1b.H1.k"].value == str(R["H1"]["k"]) and NUMBERS["bm.g1b.H3.k"].value == str(R["H3"]["k"])
    assert NUMBERS["bm.g1b.H2.k"].value == str(R["H2"]["k"]) and NUMBERS["bm.g1b.n"].value == str(R["H1"]["n"])
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "paper" / "acme" / "tables" / "tab-verification.tex")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(), encoding="utf-8", newline="\n")
    rc.write_source_recorded([args.out], "analysis/acme/make_tab_verification.py", _REC)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
