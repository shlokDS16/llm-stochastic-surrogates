"""Generate paper/acme/tables/tab-effects.tex (effect items with the Many Labs 1 human reference).

Per item: the contrast and its response (descriptive text), the pooled human effect on the scale of the simulated effect Delta (erratum E6.2: REML mean
of the site-level raw differences divided by the item's sd_within, Many Labs 1 SD units, Wald 95 percent interval), the pooled effect in the metric of the
benchmark's primary coding as a context column (REML log odds ratio or Hedges g; the published statistics are reproduced for AF, QA and NR as a check),
the between-site SD S^H in Many Labs 1 SD units with its test-inversion interval (erratum E5), and the single-site standard error c_p in the same units.
Sources, all human data and none of them model output:
  runs/human-ml1-acme/pooled_sd_units.csv  (pooled effect on Delta's scale; equal to the NUM keys hp.<item>.mu/lo/hi)
  runs/human-ml1/benchmark_table.csv and runs/human-ml1-acme/benchmark_table.csv  (pooled effect on the primary coding, primary rows)
  runs/human-ml1-acme/canonical_signs.csv  (contrast labels, metric, sign)
  runs/human-ml1-acme/arml_scales.csv  (c_p = se_single_sd_units)
  runs/human-ml1-acme/SH_sd_units.csv  (S^H in ML1-SD units: S_sd with S_sd_lo and S_sd_hi)
The script checks its cells against the \\NUM keys built by make_autonumbers.py (hp.*, cp.min, cp.max, sh.items.lo0, n.items), so the table and
the text cannot disagree.

Usage:  python analysis/acme/make_tab_effects.py [--out paper/acme/tables/tab-effects.tex]
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402  (records the files read, for the .source.json)
_REC = rc.record_reads()
from make_autonumbers import NUMBERS, _fx, _sg  # noqa: E402  (importing runs every reconciliation assert of the number blocks)

ITEMS = ["P1", "P2a", "P2b", "P2c", "P2d", "P3", "P4", "AF", "QA", "NR"]
# item -> (effect name, response and readout). Descriptive text only; the contrast labels come from canonical_signs.csv.
TEXT = {
    "P1": ("Framing of a disease problem", "Sure option chosen (0 or 1); summed answer-path probability"),
    "P2a": ("Anchoring, distance in miles", "Logarithm of the stated number; mean over the resolved digit tree"),
    "P2b": ("Anchoring, population in people", "Logarithm of the stated number; mean over the resolved digit tree"),
    "P2c": ("Anchoring, height in feet", "Logarithm of the stated number; mean over the resolved digit tree"),
    "P2d": ("Anchoring, births per day", "Logarithm of the stated number; mean over the resolved digit tree"),
    "P3": ("Sunk cost", "Rating from 1 to 9; expected rating over answer paths"),
    "P4": ("Retrospective gambler's fallacy", "Logarithm of one plus the estimated earlier rolls; mean over the resolved digit tree"),
    "AF": ("Allowed and forbidden", "Anti-speech answer (0 or 1: Yes to forbid, No to allow); summed answer-path probability"),
    "QA": ("Quote attribution", "Agreement rating from 1 to 9; expected rating over answer paths"),
    "NR": ("Norm of reciprocity", "Yes to the US question (0 or 1); summed answer-path probability, with the model's own first answer marginalised (Arm L) or sampled (Arm S)"),
}
METRIC = {"log odds ratio": "log OR", "Hedges g": "Hedges $g$"}


def _csv(rel: str) -> list[dict[str, str]]:
    with (ROOT / rel).open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def tex(x: float, nd: int = 2) -> str:
    """Number with a math minus for negative values (text-mode safe)."""
    s = _fx(x, nd)
    return f"$-${s[1:]}" if s.startswith("-") else s


def build() -> str:
    bt = {}
    for rel in ("runs/human-ml1/benchmark_table.csv", "runs/human-ml1-acme/benchmark_table.csv"):
        for r in _csv(rel):
            if r["metric"] == "primary":
                bt[r["paradigm"]] = r
    signs = {r["item"]: r for r in _csv("runs/human-ml1-acme/canonical_signs.csv")}
    scales = {r["item"]: r for r in _csv("runs/human-ml1-acme/arml_scales.csv")}
    shu = {r["item"]: r for r in _csv("runs/human-ml1-acme/SH_sd_units.csv")}
    hp = {r["item"]: r for r in _csv("runs/human-ml1-acme/pooled_sd_units.csv")}
    assert set(bt) >= set(ITEMS) and set(signs) == set(scales) == set(shu) == set(hp) == set(ITEMS)
    assert len(ITEMS) == 10 and NUMBERS["n.items"].value == "ten"
    lines = [
        "% GENERATED by analysis/acme/make_tab_effects.py from runs/human-ml1-acme/pooled_sd_units.csv, runs/human-ml1/benchmark_table.csv,",
        "% runs/human-ml1-acme/benchmark_table.csv, canonical_signs.csv, arml_scales.csv and SH_sd_units.csv. Do not edit by hand; rerun the script.",
        "% Cells: pooled human effect on Delta's scale (erratum E6.2: REML mean of site raw differences / sd_within, ML1-SD units, Wald 95 percent",
        "% interval; equal to the NUM keys hp.<item>.*); pooled effect on the primary coding (REML log OR or Hedges g; context); S^H in ML1-SD units",
        "% with test-inversion interval; c_p in ML1-SD units. A dagger marks an S^H interval that reaches zero.",
        r"{\footnotesize\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.08}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.04\textwidth}>{\raggedright\arraybackslash}p{0.20\textwidth}"
        r">{\raggedright\arraybackslash}p{0.18\textwidth}>{\raggedright\arraybackslash}p{0.13\textwidth}"
        r">{\raggedright\arraybackslash}p{0.14\textwidth}>{\raggedright\arraybackslash}p{0.13\textwidth}"
        r">{\raggedright\arraybackslash}p{0.06\textwidth}@{}}",
        r"\toprule",
        r"Item & Many Labs 1 effect and contrast ($\Cond=1$ against $\Cond=0$) & Response and readout & Pooled human effect, ML1 SD units & "
        r"Pooled effect, primary coding (context) & Between-site SD $\SH$ & Single-site SE $\cSite$ \\",
        r"\midrule",
    ]
    cps, daggers = [], 0
    for it in ITEMS:
        s, b, c, h = signs[it], bt[it], scales[it], shu[it]
        assert s["scale"] in METRIC, s["scale"]
        assert abs(float(b["mu"]) - float(s["mu_reml"])) < 1e-9  # pooled effect equals the canonical-sign file
        name, resp = TEXT[it]
        contrast = f"{name}: {s['x1']} against {s['x0']}"
        pooled = f"{tex(float(b['mu']))} ({tex(float(b['mu_lo']))} to {tex(float(b['mu_hi']))}), {METRIC[s['scale']]}"
        p = hp[it]
        assert p["orientation_ok"] == "True" and int(p["canonical_sign"]) == int(s["canonical_sign"]), it
        assert (float(p["mu_sd"]) > 0) == (float(b["mu"]) > 0), it  # both codings agree in sign
        for k, col in (("mu", "mu_sd"), ("lo", "mu_sd_lo"), ("hi", "mu_sd_hi")):
            assert _sg(p[col], 2) == NUMBERS[f"hp.{it}.{k}"].value, (it, k)  # cell equals the text key
        pooled_sd = f"{tex(float(p['mu_sd']))} ({tex(float(p['mu_sd_lo']))} to {tex(float(p['mu_sd_hi']))})"
        lo0 = float(h["S_sd_lo"]) == 0.0
        daggers += lo0
        sh = f"{tex(float(h['S_sd']))} ({tex(float(h['S_sd_lo']))} to {tex(float(h['S_sd_hi']))})" + (r"$^{\dagger}$" if lo0 else "")
        assert abs(float(h["sd_within"]) - float(c["sd_within"])) < 1e-5  # same unit in both files
        cp = float(c["se_single_sd_units"])
        cps.append(cp)
        lines.append(f"{it} & {contrast} & {resp} & {pooled_sd} & {pooled} & {sh} & {_fx(cp, 2)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    # reconcile with the text keys
    assert _fx(min(cps), 2) == NUMBERS["cp.min"].value and _fx(max(cps), 2) == NUMBERS["cp.max"].value
    words = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}
    assert words[daggers] == NUMBERS["sh.items.lo0"].value, (daggers, NUMBERS["sh.items.lo0"].value)
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "paper" / "acme" / "tables" / "tab-effects.tex")
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(), encoding="utf-8", newline="\n")
    rc.write_source_recorded([args.out], "analysis/acme/make_tab_effects.py", _REC)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
