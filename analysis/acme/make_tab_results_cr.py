"""Generate paper/acme/tables/tab-results-cr.tex (key `results-cr`): variance shares of the choice and rating items by component group, four
route columns side by side, and the H1/H3 estimates of every column.

Every cell is read from runs/ files (results_route.py lists them); no number is typed here except the interpretation bound BIAS_RULE (E7a item 3).
Blocks, equal billing (no column is primary, E7 item 2):
  (b)         Arm L frozen A1, per-type roster, 10 wordings, 4 temperatures   cell: share, second line [frozen A1 interval] (underpowered)
  (a)         Arm S A1-S, strict roster, 4 wordings, 2 temperatures, basis E2  cell: share, second line (range over leave-one-wording-out values)
  (e) Arm S   Arm S on the intersection roster (as (a))
  (e) Arm L   Arm L frozen A1 on the intersection roster, W0-W3, T 0.7/1.0     cell: share, second line (leave-one-wording-out range)
Then one block with the H1 and H3 estimates for each route column (no p-value, E7 item 5).
A group that sums several terms has no frozen interval (none is stored for a sum): its (b) cell has an empty second line.

    .venv/Scripts/python.exe -I analysis/acme/make_tab_results_cr.py [--out paper/acme/tables/tab-results-cr.tex]
Writes OUT and OUT.source.json.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import results_common as rc  # noqa: E402
import results_route as R  # noqa: E402

ITEM_TEX = {"P1": "P1", "P3": "P3", "AF": "AF", "QA": "QA", "NR": "NR"}
HEADS = {"M": "M", "O": r"\shortstack{O,\\M$\times$O}", "W": "W", "MW": r"M$\times$W",
         "WO": r"\shortstack{W$\times$O,\\M$\times$W$\times$O}", "T": r"\shortstack{T\\terms}", "res": "Residual"}
BLOCKS = [
    ("(b)", r"(b) Arm L, per-type roster, 10 wordings, 4 temperatures; share [frozen A1 interval]", "iv"),
    ("(a)", r"(a) Arm S, strict roster, 4 wordings, 2 temperatures; E2 share (range over leave-one-wording-out)", "lowo"),
    ("(e)-ArmS", r"(e) Arm S, intersection roster, 4 wordings, 2 temperatures; E2 share (range)", "lowo"),
    ("(e)-ArmL", r"(e) Arm L, intersection roster, 4 wordings, 2 temperatures; share (range)", "lowo"),
]


def cell(e: dict | None, kind: str) -> tuple[str, str]:
    """(estimate, second line): second line = frozen interval in brackets (kind iv) or leave-one-wording-out range in parentheses (kind lowo)."""
    if e is None:
        return "--", ""
    sub = ""
    if kind == "iv" and e["lo"] is not None:
        sub = f"[{R.tx(e['lo'])}, {R.tx(e['hi'])}]"
    if kind == "lowo" and e["lmin"] is not None:
        sub = f"({R.tx(e['lmin'])}, {R.tx(e['lmax'])})"
    return R.tx(e["share"]), sub


def hyp_cell(r, kind: str) -> str:
    if kind == "lowo":
        return f"{R.tx(r.estimate)} ({R.tx(r.lowo_min)}, {R.tx(r.lowo_max)})"
    return f"{R.tx(r.estimate)} [{R.tx(r.lo)}, {R.tx(r.hi)}]"


def build(route: R.Route, items: list[str]) -> str:
    cols = [g for g in R.GROUP_KEYS if g != "draw"]       # the draw component of Arm S is in Fig. shares and in the supplement table
    L = [
        "% GENERATED by analysis/acme/make_tab_results_cr.py from runs/acme-gstudy/route-table/ and the per-wording files named in analysis/acme/results_route.py.",
        "% Do not edit by hand; rerun the script. Every cell is read from those files; <outfile>.source.json lists the SHA-256 of each input.",
        r"{\footnotesize\setlength{\tabcolsep}{3.0pt}\renewcommand{\arraystretch}{1.0}",
        r"\begin{tabular}{@{}l " + "c" * len(cols) + r"@{}}", r"\toprule",
        r"Item (models) & " + " & ".join(HEADS[g] for g in cols) + r" \\", r"\midrule",
    ]
    for bi, (col, title, kind) in enumerate(BLOCKS):
        L.append(rf"\multicolumn{{{len(cols) + 1}}}{{@{{}}l}}{{\emph{{{title}}}}} \\[1pt]")
        for it in items:
            g = route.groups(col, it)
            if g is None:
                inf = route.info(col, it)
                L.append(rf"{ITEM_TEX[it]} (--) & \multicolumn{{{len(cols)}}}{{l}}{{not decomposed}} \\")
                continue
            n = route.info(col, it)["n_models"]
            cells = [cell(g.get(k), kind) for k in cols]
            L.append(f"{ITEM_TEX[it]} ({n}) & " + " & ".join(c[0] for c in cells) + r" \\[-1pt]")
            L.append(r" & " + " & ".join(c[1] for c in cells) + r" \\[0pt]")
        if bi < len(BLOCKS) - 1:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}}", r"\par\vskip 1pt",
          r"{\footnotesize\setlength{\tabcolsep}{3pt}\renewcommand{\arraystretch}{1.0}",
          r"\begin{tabular}{@{}l l r l l@{}}", r"\toprule",
          r"Route column & Items & $k$ & H1 estimate (interval or range) & H3 estimate (interval or range) \\", r"\midrule"]
    hy = route.hy
    # Reading = choice and rating items only (numeric items are not interpreted, Section 7.9). The plan's pooled set, which adds numeric items
    # (P2c in columns (b) and (e); all numeric items in (a) and (e)-Arm S), follows each reading and is labelled as that set (red-team M-1, 2026-11-08).
    spec = [("(b)", "A1", "choice_rating", "iv"), ("(b)", "A1", "all", "iv"), ("(c)", "A1", "all", "iv"),
            ("(a)", "E2", "choice_rating", "lowo"), ("(a)", "E2", "all", "lowo"),
            ("(e)-ArmS", "E2", "choice_rating", "lowo"), ("(e)-ArmS", "E2", "all", "lowo"),
            ("(e)-ArmL", "A1", "choice_rating", "iv"), ("(e)-ArmL", "A1", "all", "iv")]
    names = {"(b)": r"(b) Arm L, per-type roster", "(c)": r"(c) Arm L, G4-passing models", "(a)": r"(a) Arm S, strict roster",
             "(e)-ArmS": r"(e) Arm S, intersection", "(e)-ArmL": r"(e) Arm L, intersection"}
    for col, basis, iset, kind in spec:
        sub = hy[(hy["column"] == col) & (hy["basis"] == basis) & (hy["item_set"] == iset)]
        h1 = sub[sub["hypothesis"].isin(["H1", "H1_analogue"])]
        h3 = sub[sub["hypothesis"] == "H3"]
        assert len(h1) == 1 and len(h3) == 1, (col, basis, iset)
        a, b = h1.iloc[0], h3.iloc[0]
        dag = r"$^{\dagger}$" if col == "(e)-ArmL" else ""
        lab = names[col] + (r"$^{\ddagger}$" if col in ("(a)", "(e)-ArmS") else "")
        if col == "(c)":
            items_lab = "choice (AF, NR)"                       # the roster of (c) holds AF and NR only
        elif iset == "choice_rating":
            items_lab = "choice and rating (reading)"
        else:
            items_lab = "plan set with numeric items"
        L.append(f"{lab} & {items_lab} & {int(a.k_items)} & {hyp_cell(a, kind)}{dag} & {hyp_cell(b, kind)}{dag} " + r"\\")
    L += [r"\bottomrule", r"\end{tabular}}", r"\par\vskip 1pt"]
    notes = [
        r"Untruncated shares (a negative value is a negative variance-component estimate); models per column in parentheses; the rosters differ, so the shares are not a common estimand across columns and no column is primary.",
        r"Brackets: frozen A1 interval (underpowered). Parentheses: range of the four leave-one-wording-out values (fragility over the wordings, not an interval). No second line in (b): a sum of several terms, no interval stored.",
        rf"In the four-wording columns ((a) and (e)) differences below {R.BIAS_RULE:g} between shares or columns are not interpreted. Arm S: basis E2, whose draw noise (supplement table) is not shown, so the shares of an item sum to less than one. P3 has no order term in (a) and (e).",
        r"H1: pooled wording share (W and M$\times$W) minus pooled share of all terms containing T; H3: pooled M$\times$W minus pooled W; pooled is the mean over the $k$ items. No p-value is reported (erratum E7, item 5). The reading is the choice and rating row of each column; the row with numeric items pools the item set of the plan, including P2c, whose shares are not interpreted, and is shown only as that set.",
        r"$^{\ddagger}$ H1 analogue: T has two levels in Arm S, so it is not the preregistered H1. $^{\dagger}$ Interval from four wordings, not interpreted.",
    ]
    L.append(r"{\footnotesize\raggedright " + " ".join(notes) + r"\par}")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = rc.resolve_arg(a.out, rc.ROOT / "paper" / "acme" / "tables" / "tab-results-cr.tex")
    R.base_guard([out], a.out is not None)
    tr = rc.Tracker()
    route = R.Route(tr)
    items = R.items_order(tr, R.CR_ITEMS)
    text = build(route, items)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf8")
    rc.write_source([out], "analysis/acme/make_tab_results_cr.py", R.ROUTE, tr, extra=dict(items=items))


if __name__ == "__main__":
    main()
